"""Train and evaluate the inflation forecaster; write the JSON artifact and a model card.

Usage:
    python scripts/fetch_macro_history.py   # once, or to refresh the data
    python scripts/train_inflation.py

Outputs:
    models/inflation_model.json      weights, scaler, lambda, evaluation (reloadable)
    models/model_card_inflation.md     human-readable summary for the documentation
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from wealthpilot import inflation as inf  # noqa: E402


def model_card(art: dict, forecasts: list) -> str:
    lines = [
        "# Model card: Canadian inflation forecaster",
        "",
        f"Generated by `scripts/train_inflation.py` on {art['created']}. Data retrieved on {art['data']['retrieved_on']} "
        f"from: {', '.join(art['data']['sources'])}.",
        "",
        "## What it predicts",
        "",
        f"{art['target_definition'][0].upper()}{art['target_definition'][1:]}, for horizons of {', '.join(art['horizons'])} months, "
        "from the latest published month of Canadian CPI.",
        "",
        "## Methods compared",
        "",
        "| Method | Description |",
        "|---|---|",
    ]
    lines += [f"| `{m}` | {inf.METHOD_LABELS[m]} |" for m in inf.METHODS]
    lines += ["", "Ridge features and why they are included:", "", "| Feature | Reason |", "|---|---|"]
    lines += [f"| `{k}` | {v} |" for k, v in art["features"].items()]
    lines += ["", "## Out-of-sample results (walk-forward)", "",
              "Mean absolute error in percentage points of y/y inflation. Each forecast uses only data published "
              "before it was made. Coverage is the share of outcomes inside the 80% interval.", ""]
    for h, spec in art["horizons"].items():
        ev = spec["evaluation"]
        lines += [f"### {h} months ahead ({ev['n_forecasts']} forecasts, {ev['period']})", "",
                  "| Method | MAE | MAE 2008-2019 | MAE 2020 on | 80% interval coverage |", "|---|---|---|---|---|"]
        for m, v in ev["methods"].items():
            cov = "n/a" if v["interval_coverage"] is None else f"{v['interval_coverage']:.0%}"
            best = " **(used)**" if m == spec["method_used"] else ""
            lines.append(f"| `{m}`{best} | {v['mae']:.2f} | {v['mae_2008_2019']:.2f} | {v['mae_2020_on']:.2f} | {cov} |")
        cv = ", ".join(f"{k}: {v:.3f}" for k, v in spec["cv_mae_by_lambda"].items())
        lines += ["", f"Ridge penalty chosen by time-series cross-validation: lambda = {spec['lambda']} "
                  f"(CV mean absolute error by lambda: {cv}). Ridge skill vs no change: "
                  f"{ev['ridge_skill_vs_random_walk']:.0%}.", ""]
    lines += ["## Latest forecasts", "", "| Horizon | From | Target month | Current y/y | Forecast | 80% interval | Method |",
              "|---|---|---|---|---|---|---|"]
    for f in forecasts:
        lines.append(f"| {f.horizon_months} months | {f.origin_month} (published {f.available_from}) | {f.target_month} | "
                     f"{f.current_yoy:.2f}% | {f.forecast:.2f}% | {f.low:.2f}% to {f.high:.2f}% | `{f.method}` |")
    lines += ["", "## Findings and limits", "",
              "- The ridge model on macro features does not beat simple rules out of sample. The method used is the "
              "one with the lowest walk-forward error, and the application says which one it is.",
              "- Errors are much larger since 2020 (pandemic and the 2021-2023 inflation surge) than in 2008-2019; "
              "intervals are built from past errors and widen accordingly.",
              "- Macro series from FRED are latest revised values, not the values first published; Canadian CPI is "
              "not revised, so the target itself is unaffected.",
              "- Forecasts inform scenarios and real-return estimates. They are not used to time markets.", ""]
    return "\n".join(lines)


def main() -> None:
    history = pd.read_csv(ROOT / "data" / "external" / "macro_history.csv", parse_dates=["date"])
    art = inf.train(history)
    inf.save(art)
    forecasts = [inf.forecast(history, art, h) for h in inf.HORIZONS]
    card = ROOT / "models" / "model_card_inflation.md"
    card.write_text(model_card(art, forecasts))
    for f in forecasts:
        print(f"{f.horizon_months:>2}m: {f.current_yoy:.2f}% -> {f.forecast:.2f}% [{f.low:.2f}, {f.high:.2f}] via {f.method}")
    print(f"wrote {inf.ARTIFACT} and {card}")


if __name__ == "__main__":
    main()
