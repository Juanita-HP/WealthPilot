"""Check the text analyzer against the official numbers.

Every decision the analyzer reads in a text (policy rate raised to 2.5%, CPI at
3.1%) can be checked against the official data series we already store, so this
evaluation needs no hand labels:

* Bank of Canada rate decisions vs series V39079 (target for the overnight rate)
* Federal Reserve decisions vs DFEDTARU (upper limit of the federal funds target range)
* Statistics Canada CPI releases vs STATIC_TOTALCPICHANGE (total CPI, % y/y)

Labour Force Survey and GDP releases are counted but not verifiable with our series.

Output: models/macro_eval.json and models/macro_eval.md
Usage: python scripts/eval_macro.py
"""

from __future__ import annotations

import json
import re
import sys
from datetime import date
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from wealthpilot import data, macro_news as mn  # noqa: E402

MONTHS = {m: i for i, m in enumerate(["January", "February", "March", "April", "May", "June", "July", "August",
                                      "September", "October", "November", "December"], 1)}


def truth(item: dict) -> dict | None:
    d = item["analysis"].get("decision")
    when = pd.Timestamp(item["published_at"][:10])
    title = item["title"]
    if item["publisher"] in ("Bank of Canada", "Federal Reserve") and d and d["kind"] == "policy_rate":
        sid = "V39079" if item["publisher"] == "Bank of Canada" else "DFEDTARU"
        s = data.load_macro_history(sid, point_in_time=False).dropna()
        before = s[s.index < when]
        after = s[(s.index > when) & (s.index <= when + pd.Timedelta(days=10))]
        if before.empty or after.empty:
            return None
        b, a = float(before.iloc[-1]), float(after.iloc[-1])
        return {"series": sid, "value": a, "direction": "up" if a > b else "down" if a < b else "unchanged"}
    m = re.match(r"Consumer Price Index, (\w+) (\d{4})", title)
    if m and m.group(1) in MONTHS:
        s = data.load_macro_history("STATIC_TOTALCPICHANGE", point_in_time=False).dropna()
        ref = pd.Timestamp(int(m.group(2)), MONTHS[m.group(1)], 1)
        if ref not in s.index:
            return None
        prev = ref - pd.DateOffset(months=1)
        v, p = float(s.loc[ref]), float(s.loc[prev]) if prev in s.index else None
        direction = None if p is None else ("unchanged" if abs(v - p) < 0.2 else "up" if v > p else "down")
        return {"series": "STATIC_TOTALCPICHANGE", "value": v, "direction": direction}
    return None


def main() -> None:
    items = [i.to_dict() for i in mn.collect(days=400, per_feed=40)]
    rows, unverifiable = [], 0
    for it in items:
        d = it["analysis"].get("decision")
        expected_kind = ("policy_rate" if re.search(r"(policy rate|FOMC statement)", it["title"], re.I)
                         else "cpi" if it["title"].startswith("Consumer Price Index") else None)
        t = truth(it) if expected_kind else None
        if expected_kind is None:
            unverifiable += d is not None
            continue
        if t is None:
            continue
        rows.append({"title": it["title"], "date": it["published_at"][:10], "text_status": it["text_status"],
                     "found": d is not None and d["kind"] == expected_kind,
                     "value_read": d and d.get("value"), "value_true": t["value"],
                     "value_ok": bool(d) and d.get("value") is not None and abs(d["value"] - t["value"]) < 1e-6,
                     "direction_read": d and d["direction"], "direction_true": t["direction"],
                     "direction_ok": bool(d) and t["direction"] is not None and d["direction"] == t["direction"],
                     "series": t["series"]})
    n = len(rows)
    out = {"analyzer": mn.ANALYZER_VERSION, "run_on": date.today().isoformat(), "n_checked": n,
           "n_items_collected": len(items), "n_text_read": sum(i["text_status"] == "ok" for i in items),
           "decision_found": sum(r["found"] for r in rows) / n if n else None,
           "value_accuracy": sum(r["value_ok"] for r in rows) / n if n else None,
           "direction_accuracy": sum(r["direction_ok"] for r in rows) / n if n else None,
           "other_decisions_not_verifiable": unverifiable, "rows": rows}
    (ROOT / "models").mkdir(exist_ok=True)
    (ROOT / "models" / "macro_eval.json").write_text(json.dumps(out, indent=2, ensure_ascii=False))
    lines = ["# Official-text analyzer: check against official data series", "",
             f"Analyzer `{out['analyzer']}`, run on {out['run_on']}. Generated by `scripts/eval_macro.py`.", "",
             "Each decision read in a text is compared with the official series published by the same institution, "
             "so no hand labels are needed. A miss here means the text was misread.", "",
             f"* Items collected: {out['n_items_collected']} (full text read for {out['n_text_read']})",
             f"* Decisions checkable against a series: {n}",
             f"* Decision found in the text: {out['decision_found']:.0%}" if n else "* none",
             f"* Value read correctly: {out['value_accuracy']:.0%}" if n else "",
             f"* Direction read correctly: {out['direction_accuracy']:.0%}" if n else "",
             f"* Other decisions read but not checkable with our series (jobs, GDP): {unverifiable}", "",
             "| Date | Text | Read | True (series) | OK |", "|---|---|---|---|---|"]
    for r in rows:
        ok = "yes" if r["found"] and r["value_ok"] and r["direction_ok"] else "**no**"
        lines.append(f"| {r['date']} | {r['title'][:70]} | {r['direction_read']} {r['value_read']} | "
                     f"{r['direction_true']} {r['value_true']} ({r['series']}) | {ok} |")
    lines += ["", "Limits: the feeds only go back a few months to a year, so the sample is small; "
              "the rules were written while reading recent releases, so a later sample is the real test."]
    (ROOT / "models" / "macro_eval.md").write_text("\n".join(l for l in lines if l is not None) + "\n")
    print(json.dumps({k: v for k, v in out.items() if k != "rows"}, indent=2))
    for r in rows:
        if not (r["found"] and r["value_ok"] and r["direction_ok"]):
            print("MISS", r)


if __name__ == "__main__":
    main()
